import { useEffect } from 'react';
import { DollarSign } from 'lucide-react';
import api        from '../../services/api';
import useApi     from '../../hooks/useApi';
import Card, { CardBody } from '../../components/ui/Card';
import Badge      from '../../components/ui/Badge';
import Spinner    from '../../components/ui/Spinner';
import EmptyState from '../../components/ui/EmptyState';
import { formatDate, formatCurrency } from '../../utils/helpers';
import tStyles    from './Teacher.module.css';
import styles     from '../admin/Page.module.css';

const Salary = () => {
  const { data: salaries, loading, execute: load } = useApi(() => api.get('/salaries'), []);
  useEffect(() => { load(); }, [load]);

  const total = (salaries||[]).reduce((sum, s) => sum + parseFloat(s.total_salary || 0), 0);
  const paid  = (salaries||[]).filter(s => s.status === 'paid').reduce((sum, s) => sum + parseFloat(s.total_salary || 0), 0);

  return (
    <div className={tStyles.page}>
      <h1 className={tStyles.title}>My Salary</h1>

      {/* Summary */}
      {!loading && (salaries||[]).length > 0 && (
        <div style={{ display:'flex', gap:12, flexWrap:'wrap' }}>
          {[
            { label:'Total Earned',  value: formatCurrency(total), color:'#2563eb' },
            { label:'Total Paid',    value: formatCurrency(paid),  color:'#16a34a' },
            { label:'Total Pending', value: formatCurrency(total - paid), color:'#d97706' },
          ].map(({ label, value, color }) => (
            <Card key={label} style={{ flex:'1 1 160px' }}>
              <CardBody>
                <div style={{ fontSize:'1.2rem', fontWeight:700, color }}>{value}</div>
                <div style={{ fontSize:'0.8rem', color:'#64748b', marginTop:2 }}>{label}</div>
              </CardBody>
            </Card>
          ))}
        </div>
      )}

      <Card>
        <CardBody>
          {loading ? <Spinner /> : !(salaries||[]).length ? (
            <EmptyState icon={DollarSign} title="No salary records yet" description="Salary records are generated by the administrator each month." />
          ) : (
            <div className={styles.tableWrap}>
              <table className={styles.table}>
                <thead>
                  <tr><th>Month</th><th>Students</th><th>Rate</th><th>Total</th><th>Status</th><th>Paid Date</th></tr>
                </thead>
                <tbody>
                  {salaries.map(s => (
                    <tr key={s.id}>
                      <td style={{ fontWeight:600 }}>{s.salary_month?.slice(0,7)}</td>
                      <td>{s.active_students}</td>
                      <td>{formatCurrency(s.rate_per_student)}</td>
                      <td style={{ fontWeight:700, color:'#1e293b' }}>{formatCurrency(s.total_salary)}</td>
                      <td><Badge status={s.status} /></td>
                      <td>{s.payment_date ? formatDate(s.payment_date) : '—'}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </CardBody>
      </Card>
    </div>
  );
};

export default Salary;
